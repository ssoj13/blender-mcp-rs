/// One tool, declared once, consumed by both processes.
pub struct ToolDef {
    /// MCP tool name, e.g. `obj_list`.
    pub name: &'static str,
    /// Shown to the model in `tools/list`.
    pub description: &'static str,
    /// JSON Schema of the params struct, generated by `schemars`. Server side only.
    pub schema: fn() -> Value,
    /// Runs inside Blender, on the main thread, with the GIL held.
    pub handler: fn(Python<'_>, Value) -> PyResult<Value>,
}

inventory::collect!(ToolDef);

/// Declare a tool: params struct + description + body, in one place.
///
/// The params type must derive `Deserialize` and `schemars::JsonSchema`; doc
/// comments on its fields become the `description` of each JSON Schema property.
///
/// ## The error contract
/// A call that could not do what it was asked returns `Err` — the object was not
/// found, the type was invalid, the prerequisite was missing. `Err` reaches the
/// model as an MCP error with `isError` set, so it cannot be mistaken for success.
///
/// **Never report a failure as `Ok(json!({"error": ...}))`.** That is a *successful*
/// result whose text merely mentions an error, and a model reads past it and keeps
/// going down a broken path. It is also invisible to the compiler.
///
/// The one exception is a **batch item**: when a call operates on many targets and
/// some succeed, per-item failures are data, and belong in the `results` array:
///
/// ```ignore
/// results.push(json!({ "name": name, "error": "not found" }));  // fine: partial success
/// return Err(PyValueError::new_err(format!("object not found: {name}")));  // single target
/// ```
#[macro_export]
macro_rules! tool {
    ($name:literal, $desc:literal, $params:ty, $handler:expr) => {
        inventory::submit! {
            $crate::tools::ToolDef {
                name: $name,
                description: $desc,
                schema: || {
                    serde_json::to_value(schemars::schema_for!($params))
                        .expect("schemars always produces valid JSON")
                },
                handler: |py: pyo3::Python<'_>, v: serde_json::Value| {
                    let p: $params = serde_json::from_value(v).map_err(|e| {
                        pyo3::exceptions::PyValueError::new_err(format!(
                            concat!("invalid params for `", $name, "`: {}"), e
                        ))
                    })?;
                    let f: fn(pyo3::Python<'_>, $params) -> pyo3::PyResult<serde_json::Value> =
                        $handler;
                    f(py, p)
                },
            }
        }
    };
}

/// Every registered tool. Order is not guaranteed by `inventory`.
pub fn all() -> impl Iterator<Item = &'static ToolDef> {
    inventory::iter::<ToolDef>.into_iter()
}

pub fn find(name: &str) -> Option<&'static ToolDef> {
    all().find(|t| t.name == name)
}

/// Blender-side entry point, called from Python as `blender_mcp.execute_tool`.
///
/// The registry is the only dispatch path. An unknown name is an error, not a
/// fallback: a silent fallback would let a typo or a stale client look like it
/// worked, which is exactly the class of bug that hides for days.
pub fn execute_tool(py: Python<'_>, method: &str, params_json: &str) -> PyResult<String> {
    let tool = find(method).ok_or_else(|| {
        pyo3::exceptions::PyValueError::new_err(format!("unknown tool: {method}"))
    })?;

    let params: Value = serde_json::from_str(params_json).map_err(|e| {
        pyo3::exceptions::PyValueError::new_err(format!("invalid params JSON: {e}"))
    })?;

    let out = (tool.handler)(py, params)?;
    serde_json::to_string(&out)
        .map_err(|e| pyo3::exceptions::PyRuntimeError::new_err(format!("serialize result: {e}")))
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeSet;

    /// `inventory` accepts duplicate submissions happily, and `find()` would then
    /// silently pick whichever one the linker happened to order first.
    #[test]
    fn names_are_unique() {
        let mut seen = BTreeSet::new();
        for tool in super::all() {
            assert!(seen.insert(tool.name), "duplicate tool name: {}", tool.name);
        }
        assert!(!seen.is_empty(), "registry is empty — is inventory linked?");
    }

    /// The name, description and schema are what the model sees in `tools/list`.
    /// An empty one is a silently useless tool.
    #[test]
    fn every_tool_is_well_formed() {
        for tool in super::all() {
            assert!(!tool.name.is_empty(), "tool with empty name");
            assert!(
                !tool.description.is_empty(),
                "{}: empty description",
                tool.name
            );
            let schema = (tool.schema)();
            assert_eq!(
                schema.get("type").and_then(|t| t.as_str()),
                Some("object"),
                "{}: params schema must be a JSON object",
                tool.name
            );
        }
    }

    /// Guards the error contract documented on `tool!`: a failed call must return
    /// `Err`, never `Ok(json!({"error": ...}))` — the latter reaches the model as a
    /// *successful* result that merely mentions an error, and it reads straight past
    /// it. The compiler cannot see that mistake, so this scans for it.
    ///
    /// Per-item failures inside a batch are legitimate data and use
    /// `results.push(json!({... "error": ...}))`, which this pattern does not match.
    #[test]
    fn no_failure_is_reported_as_success() {
        let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("src/tools");
        let entries = std::fs::read_dir(&dir).expect("src/tools must be readable");

        let mut offenders = Vec::new();
        for entry in entries.flatten() {
            let path = entry.path();
            if path.extension().and_then(|e| e.to_str()) != Some("rs") {
                continue;
            }
            // This file documents the anti-pattern in prose; skip it.
            if path.file_name().and_then(|f| f.to_str()) == Some("mod.rs") {
                continue;
            }
            let src = std::fs::read_to_string(&path).expect("tool module must be readable");
            for (i, line) in src.lines().enumerate() {
                let t = line.trim_start();
                if t.starts_with("//") {
                    continue;
                }
                let normalised = t.replace(' ', "");
                if normalised.contains("Ok(json!({\"error\"") {
                    offenders.push(format!(
                        "{}:{}: {}",
                        path.file_name().and_then(|f| f.to_str()).unwrap_or("?"),
                        i + 1,
                        t
                    ));
                }
            }
        }

        assert!(
            offenders.is_empty(),
            "a failed call must return Err, not a successful result carrying an \
             \"error\" key (see the error contract on `tool!`):\n  {}",
            offenders.join("\n  ")
        );
    }
}
