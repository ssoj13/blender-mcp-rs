//! Tool registry — the single source of truth for every MCP tool.
//!
//! ## Why this exists
//! A tool used to be declared in three places that the compiler could not keep in
//! sync: a hand-written JSON schema in `mcp_catalog.rs`, an arm of a `match` in
//! `bpy_dispatch/mod.rs`, and the implementation itself. Here it is declared once.
//!
//! ## The two consumers
//! The catalog is needed in the MCP **server** process (`main.rs`), which has no
//! `bpy`. Execution happens inside **Blender** (the `.pyd`). Both are Rust and both
//! are built from this one crate (`crate-type = ["cdylib", "rlib"]`), so a single
//! registry serves both:
//!
//! ```text
//!                    tools::all()   (inventory)
//!                   /                         \
//!      server (main.rs)                     Blender (lib.rs)
//!      name + description + schema          name -> handler(py, params)
//!      -> rmcp ToolRouter                   -> bpy via PyO3
//! ```
//!
//! The server side needs **no per-tool code**: one blanket route forwards
//! `params -> IPC -> Blender -> Output` for every tool in the registry.
//!
//! ## Registration
//! `inventory` collects submissions via linker sections. This was verified to work
//! inside the `.pyd` loaded by Blender's bundled CPython on Windows — tools declared
//! in separate modules are picked up with no central registration list.

